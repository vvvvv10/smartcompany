-- 42: 普通用户收回「角色管理 / 授权矩阵」——USER 不再持 role:manage
--
-- 背景：角色管理、授权矩阵（以及同组的系统管理员、组织架构）都是管理口径的
-- 页签，线上曾被手工给 USER 勾上 role:manage，普通成员因此能进这些页签看
-- 全量、还能改授权矩阵。种子（23 号）从未给 USER 授过它——这次把期望配置
-- 固化下来，避免重灌或别的实例又出现同样的手工勾选。
--
-- 摘掉后权限中心的可见页签变为：
--   * 概览 —— 人人可见（我的权限点 + 全目录自助申请/删除）；
--   * 团队 —— 人人可见，分两套口径：持 role:manage 的管理者看全量并可增删改；
--     普通成员只读，且只看自己所在的团队（GET /api/users/me/joined-teams，
--     行级边界 = 本人，服务端过滤）；
--   * 角色管理 / 授权矩阵 / 系统管理员 / 组织架构 —— 需 role:manage。
--
-- 连带效果（都已有防御，无需改代码）：/api/admin/roles、/matrix、/teams、
-- /system-admins、/overview 对普通成员一律 403；前端页内按 role:manage 过滤，
-- 不拉这些接口。审批中心不受影响（permission:review 保持不动，它的列表按
-- 查看者圈范围，普通成员进去是空列表）。
--
-- 幂等：DELETE 无命中即为空操作；fresh init 时 USER 本就没有这项授权。
-- ============================================================
DELETE FROM role_permissions
 WHERE role_code = 'USER' AND permission_code = 'role:manage';
